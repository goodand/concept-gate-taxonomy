"""H1a decision-basis policy contract (D-H1a-10 Q10.2).

WHY THIS MODULE EXISTS
----------------------
The 40-trial cohort of 2026-08-03 was ruled NON-IDENTIFYING (Q10=E). Both arms
kept a common Q7 warrant rule forbidding source_kind priority, recency,
authority and liveness as tie-breakers, so `PROHIBITION_REMOVED` never actually
permitted the mechanism the manipulation targets.

`assert_no_residual_prohibition` in `_h1a_contract.py` PASSED throughout, and
`test_guard_precision_the_clean_template_passes` actively certified the
template as clean. The guard was not buggy. It asserted the wrong proposition:

    asserted:  "Q1's clause bytes are absent from REMOVED"
    needed:    "no equivalent prohibition remains in REMOVED"

Q10.2 orders that raised, and explicitly forbids doing it with a closed keyword
list, because an equivalent prohibition can be phrased as any paraphrase and
lexical completeness cannot be certified. The fix is structural: make a typed
policy object canonical, generate the prompt FROM it, and check the policy
rather than the prose.

    typed policy schema -> deterministic renderer -> structural assertions
    -> deductive policy check -> (LLM semantic lint) -> human sign-off

This module owns the first four. The LLM lint is advisory only (Q10.2:
"sole certification oracle" is an inappropriate role) and is not implemented
here.

WHAT IS STILL UNDECIDED
-----------------------
Q11 (`correspondence/DESIGN_REQUEST_H1a_allowed_rendering.md`) asks what an
axis in state `allowed` renders as: an explicit permission sentence, or
silence. That is a manipulation-surface question, so P7 forbids the operating
session settling it. `REMOVED_ALLOWED_RENDERING` is therefore None, and
`assert_freezable()` refuses to let anything freeze while it is None. Rendering
still works when a mode is passed explicitly, so tests can exercise both
branches without the experiment having chosen one.
"""

from __future__ import annotations

import textwrap

# Wrapping matches the surrounding template's existing style (76-column body,
# two-space continuation under a "- " bullet). Matching it is deliberate: R1
# mandates removing four axes from the list, not reflowing the prompt, and an
# unwrapped single line would be a surface change the ruling never asked for.
_WRAP_WIDTH = 76
_BULLET_INDENT = "  "

# --------------------------------------------------------------------------
# Policy axes
# --------------------------------------------------------------------------
# The seven decision bases named by D-H1a-10 Q10.2's `decision_basis_policy`.
# These are POLICY IDs, not prompt strings. Prose is generated from them; it
# never defines them.
AXES = (
    "evidence_count",
    "source_order",
    "outside_knowledge",
    "source_kind_priority",
    "recency",
    "authority",
    "liveness",
)

# The axes Q1's manipulation targets. D-H1a-10-R1 removes exactly these four
# from the common Q7 list; the other three stay forbidden in both arms.
TARGET_AXES = frozenset(
    {"source_kind_priority", "recency", "authority", "liveness"}
)
NONTARGET_AXES = frozenset(AXES) - TARGET_AXES

ARMS = ("PROHIBITION_KEPT", "PROHIBITION_REMOVED")
_ARM_KEY = {"PROHIBITION_KEPT": "kept", "PROHIBITION_REMOVED": "removed"}

FORBIDDEN = "forbidden"
ALLOWED = "allowed"

# --------------------------------------------------------------------------
# Carriers -- which prompt section expresses a given axis
# --------------------------------------------------------------------------
# This is the field the old guard lacked, and its absence is why blocker #16
# and Q10 were the same defect twice. Knowing an axis's STATE is not enough;
# the check that matters is which section CARRIES that state, and whether any
# axis is carried twice.
CARRIER_Q1 = "Q1_LIVENESS_CLAUSE"          # KEPT only; Q1=B / Q5=B frozen bytes
CARRIER_Q7 = "Q7_TIEBREAKER_LIST"          # both arms; generated by this module
CARRIER_BOUNDARY = "PACKET_BOUNDARY"       # both arms; Q3=B template preamble
CARRIER_PERMISSION = "Q11_PERMISSION"      # REMOVED only; exists iff Q11 says so

CARRIERS = (CARRIER_Q1, CARRIER_Q7, CARRIER_BOUNDARY, CARRIER_PERMISSION)

# --------------------------------------------------------------------------
# The policy object (D-H1a-10 Q10.2, extended with `carriers`)
# --------------------------------------------------------------------------
# `carriers` is DECLARED here and verified against rendered text by
# `assert_declared_carriers_match_rendered_text`. A carrier that appears in the
# prose but not in this declaration is a violation, and so is the reverse.
#
# Note `outside_knowledge` honestly declares TWO carriers. The Q3=B packet
# boundary sentence already forbids using outside knowledge at all, and the Q7
# list forbids using it as a tie-breaker -- the second is subsumed by the
# first. That duplication is harmless because the axis is forbidden in BOTH
# arms, so it cannot create or destroy an arm contrast. The single-carrier rule
# is enforced only where it matters: on axes whose state differs between arms
# (`assert_manipulated_axes_have_exactly_one_carrier`). Declaring the
# duplication rather than hiding it is the point -- Q10's defect was an
# UNDECLARED second carrier on a manipulated axis.
DECISION_BASIS_POLICY: dict[str, dict] = {
    "evidence_count": {
        "kept": FORBIDDEN, "removed": FORBIDDEN,
        "carriers": (CARRIER_Q7,),
    },
    "source_order": {
        "kept": FORBIDDEN, "removed": FORBIDDEN,
        "carriers": (CARRIER_Q7,),
    },
    "outside_knowledge": {
        "kept": FORBIDDEN, "removed": FORBIDDEN,
        "carriers": (CARRIER_BOUNDARY, CARRIER_Q7),
    },
    "source_kind_priority": {
        "kept": FORBIDDEN, "removed": ALLOWED,
        "carriers": (CARRIER_Q1,),
    },
    "recency": {
        "kept": FORBIDDEN, "removed": ALLOWED,
        "carriers": (CARRIER_Q1,),
    },
    "authority": {
        "kept": FORBIDDEN, "removed": ALLOWED,
        "carriers": (CARRIER_Q1,),
    },
    "liveness": {
        "kept": FORBIDDEN, "removed": ALLOWED,
        "carriers": (CARRIER_Q1,),
    },
}

# --------------------------------------------------------------------------
# Q11 PENDING -- fail-closed
# --------------------------------------------------------------------------
# None until an external ruling answers Q11. `assert_freezable()` refuses to
# freeze while this is None, so no prompt can reach a trial without the ruling.
RENDERING_MODES = ("silence", "explicit_permission")
REMOVED_ALLOWED_RENDERING: str | None = None

# Surface tokens that express each axis, per language. Used ONLY to verify that
# rendered prose matches the declared policy -- never to define policy, and
# never as the primary proof of absence (Q10.2 forbids that). Incompleteness
# here degrades the cross-check, not the structural guarantee: the guarantee
# comes from generating prose from the policy object in the first place.
AXIS_SURFACE_TOKENS: dict[str, tuple[str, ...]] = {
    "evidence_count": ("evidence item count", "evidence count"),
    "source_order": ("source order",),
    "outside_knowledge": ("outside knowledge", "external sources"),
    "source_kind_priority": ("source_kind priority", "source_kind", "우선순위"),
    "recency": ("recency", "더 최신", "최신인지"),
    "authority": ("authority", "권위"),
    "liveness": ("liveness", "살아있는"),
}

_Q7_AXIS_PHRASE = {
    "evidence_count": "evidence item count",
    "source_order": "source order",
    "outside_knowledge": "outside knowledge",
    "source_kind_priority": "source_kind priority",
    "recency": "recency",
    "authority": "authority",
    "liveness": "liveness",
}


def _normalize_ws(text: str) -> str:
    """Collapse all whitespace runs to single spaces, lowercased.

    Required, not cosmetic. Surface tokens are multi-word phrases ("outside
    knowledge", "evidence item count") and the template wraps at 76 columns, so
    a phrase can be split across a newline plus indent. Matching raw text would
    then miss an axis that IS present -- a false negative in the exact guard
    whose predecessor already failed this experiment once. Caught by
    `test_nontarget_bullet_names_all_three_axes_in_both_arms` when wrapping was
    introduced.
    """
    return " ".join(text.split()).lower()


class PolicyContractError(Exception):
    """A structural or deductive policy check failed. Never proceed."""


class Q11Undecided(PolicyContractError):
    """An axis is `allowed` but Q11 has not ruled how that renders."""


# --------------------------------------------------------------------------
# Deterministic renderer
# --------------------------------------------------------------------------
def _q7_forbidden_axes(arm: str) -> list[str]:
    """Axes this arm forbids *via the Q7 list*, in AXES order (deterministic)."""
    key = _ARM_KEY[arm]
    return [
        a for a in AXES
        if CARRIER_Q7 in DECISION_BASIS_POLICY[a]["carriers"]
        and DECISION_BASIS_POLICY[a][key] == FORBIDDEN
    ]


def _allowed_axes(arm: str) -> list[str]:
    key = _ARM_KEY[arm]
    return [a for a in AXES if DECISION_BASIS_POLICY[a][key] == ALLOWED]


def _join_english(phrases: list[str]) -> str:
    if len(phrases) == 1:
        return phrases[0]
    if len(phrases) == 2:
        return f"{phrases[0]} or {phrases[1]}"
    return ", ".join(phrases[:-1]) + f", or {phrases[-1]}"


def _bullet(body: str) -> str:
    """Wrap one policy sentence as a bullet in the template's existing style."""
    return "\n".join(
        textwrap.wrap(
            f"- {body}",
            width=_WRAP_WIDTH,
            subsequent_indent=_BULLET_INDENT,
            break_long_words=False,
            break_on_hyphens=False,
        )
    )


def render_policy_block(arm: str, allowed_rendering: str | None = None) -> list[tuple[str, str]]:
    """Return [(carrier_id, sentence)] for this arm's policy-bearing prose.

    Returning provenance pairs rather than a blob is what makes Q10.2's
    requirement 5 ("every rendered policy sentence traceable to its policy ID")
    checkable instead of merely asserted.

    `allowed_rendering` defaults to the module-level (Q11-pending) value.
    Passing it explicitly is how tests exercise both branches without the
    experiment having chosen one.
    """
    if arm not in ARMS:
        raise ValueError(f"arm must be one of {ARMS}, got {arm!r}")
    mode = allowed_rendering if allowed_rendering is not None else REMOVED_ALLOWED_RENDERING

    out: list[tuple[str, str]] = []

    forbidden = _q7_forbidden_axes(arm)
    if forbidden:
        phrase = _join_english([_Q7_AXIS_PHRASE[a] for a in forbidden])
        out.append((
            CARRIER_Q7,
            _bullet(
                f"Do not break ties using {phrase} unless that priority is "
                f"directly stated inside an evidence item's text."
            ),
        ))

    allowed = _allowed_axes(arm)
    if allowed:
        if mode is None:
            raise Q11Undecided(
                f"{arm} has axes in state `allowed` ({', '.join(allowed)}) but "
                f"REMOVED_ALLOWED_RENDERING is None -- Q11 has not ruled "
                f"whether `allowed` renders as an explicit permission sentence "
                f"or as silence. See "
                f"correspondence/DESIGN_REQUEST_H1a_allowed_rendering.md"
            )
        if mode not in RENDERING_MODES:
            raise PolicyContractError(
                f"REMOVED_ALLOWED_RENDERING must be one of {RENDERING_MODES} "
                f"or None, got {mode!r}"
            )
        if mode == "explicit_permission":
            phrase = _join_english([_Q7_AXIS_PHRASE[a] for a in allowed])
            out.append((
                CARRIER_PERMISSION,
                _bullet(
                    f"If the packet's own evidence texts differ in {phrase}, "
                    f"you may take that difference into account when judging "
                    f"warrant."
                ),
            ))
        # mode == "silence": emit nothing. The axis is neither forbidden nor
        # permitted in prose. Q11 option A.
    return out


def render_policy_text(arm: str, allowed_rendering: str | None = None) -> str:
    return "\n".join(sentence for _, sentence in render_policy_block(arm, allowed_rendering))


# --------------------------------------------------------------------------
# Structural assertions (Q10.2's hard-guard list, items 1-6)
# --------------------------------------------------------------------------
def assert_target_axis_states() -> None:
    """(1) target axes: KEPT=forbidden, REMOVED=allowed."""
    for axis in sorted(TARGET_AXES):
        p = DECISION_BASIS_POLICY[axis]
        if p["kept"] != FORBIDDEN or p["removed"] != ALLOWED:
            raise PolicyContractError(
                f"target axis {axis!r} must be kept=forbidden/removed=allowed, "
                f"got kept={p['kept']!r}/removed={p['removed']!r}"
            )


def assert_nontarget_axes_are_arm_invariant() -> None:
    """(2) non-target axes are identical across arms."""
    for axis in sorted(NONTARGET_AXES):
        p = DECISION_BASIS_POLICY[axis]
        if p["kept"] != p["removed"]:
            raise PolicyContractError(
                f"non-target axis {axis!r} differs across arms "
                f"(kept={p['kept']!r}, removed={p['removed']!r}) -- only the "
                f"preregistered target set may differ"
            )


def assert_arm_difference_is_exactly_the_target_set() -> None:
    """(3) the set of axes differing between arms == TARGET_AXES, exactly."""
    differing = {
        a for a in AXES
        if DECISION_BASIS_POLICY[a]["kept"] != DECISION_BASIS_POLICY[a]["removed"]
    }
    if differing != set(TARGET_AXES):
        raise PolicyContractError(
            f"arm-differing axes {sorted(differing)} != preregistered target "
            f"set {sorted(TARGET_AXES)}"
        )


def assert_manipulated_axes_have_exactly_one_carrier() -> None:
    """(4) no duplicate prohibition of a manipulated axis.

    This is the assertion whose absence produced blocker #16 and then Q10.
    An axis whose state differs between arms must be expressed by exactly one
    section; two carriers means removing one still leaves the other, which is
    precisely how `PROHIBITION_REMOVED` stayed prohibited twice over.
    """
    for axis in sorted(TARGET_AXES):
        carriers = DECISION_BASIS_POLICY[axis]["carriers"]
        if len(carriers) != 1:
            raise PolicyContractError(
                f"manipulated axis {axis!r} has {len(carriers)} carriers "
                f"{carriers} -- must be exactly 1, or removing one leaves the "
                f"other in force (this is the Q10 defect)"
            )


def assert_declared_carriers_match_rendered_text(
    rendered: dict[str, str], allowed_rendering: str | None = None
) -> None:
    """(5)+(6) rendered prose agrees with the declared policy, both directions.

    Forward: an axis forbidden in an arm must be named somewhere in that arm.
    Reverse: an axis ALLOWED in an arm must NOT be named by a prohibition-bearing
    section in that arm -- this is what catches a residual prohibition
    regardless of how it is phrased, because it tests the axis's presence in the
    arm rather than matching a known sentence.
    """
    mode = allowed_rendering if allowed_rendering is not None else REMOVED_ALLOWED_RENDERING
    for arm in ARMS:
        if arm not in rendered:
            raise PolicyContractError(f"rendered text missing for arm {arm!r}")
        haystack = _normalize_ws(rendered[arm])
        generated = {cid for cid, _ in render_policy_block(arm, mode)}
        key = _ARM_KEY[arm]

        for axis in AXES:
            state = DECISION_BASIS_POLICY[axis][key]
            tokens = AXIS_SURFACE_TOKENS[axis]
            present = any(_normalize_ws(t) in haystack for t in tokens)

            if state == FORBIDDEN and not present:
                raise PolicyContractError(
                    f"{arm}: axis {axis!r} is declared {FORBIDDEN} but no "
                    f"surface token {tokens} appears -- the policy claims a "
                    f"constraint the prompt does not express"
                )
            if state == ALLOWED and present and CARRIER_PERMISSION not in generated:
                raise PolicyContractError(
                    f"{arm}: axis {axis!r} is declared {ALLOWED} but a surface "
                    f"token {tokens} appears and no permission sentence was "
                    f"generated -- a residual prohibition is present. This is "
                    f"the check the old byte-absence guard did not make."
                )


# --------------------------------------------------------------------------
# Deductive policy check (Q10.2; reproduces D-H1a-10 sec 3 independently)
# --------------------------------------------------------------------------
def target_mechanism_allowed(arm: str) -> bool:
    """M_allowed = not Q1_forbids_target and not Q7_forbids_target.

    Derived from the policy object rather than restated, so this function
    reproduces D-H1a-10 sec 3's proof instead of trusting it.
    """
    key = _ARM_KEY[arm]
    q1 = any(
        DECISION_BASIS_POLICY[a][key] == FORBIDDEN
        and CARRIER_Q1 in DECISION_BASIS_POLICY[a]["carriers"]
        for a in TARGET_AXES
    )
    q7 = any(
        DECISION_BASIS_POLICY[a][key] == FORBIDDEN
        and CARRIER_Q7 in DECISION_BASIS_POLICY[a]["carriers"]
        for a in TARGET_AXES
    )
    return (not q1) and (not q7)


def truth_table() -> list[dict]:
    """All four (Q1, Q7_target) cells and whether the target path opens.

    Reproduces D-H1a-10 sec 6's table from the formalization, not by copying it.
    """
    return [
        {"q1_forbids": q1, "q7_forbids": q7, "m_allowed": (not q1) and (not q7)}
        for q1 in (True, False)
        for q7 in (True, False)
    ]


def deductive_check() -> dict:
    """Verify the four propositions Q10.2 names, and return the evidence."""
    kept = target_mechanism_allowed("PROHIBITION_KEPT")
    removed = target_mechanism_allowed("PROHIBITION_REMOVED")
    nontarget_equal = all(
        DECISION_BASIS_POLICY[a]["kept"] == DECISION_BASIS_POLICY[a]["removed"]
        for a in NONTARGET_AXES
    )
    unsatisfiable = [
        a for a in AXES
        if DECISION_BASIS_POLICY[a]["kept"] not in (FORBIDDEN, ALLOWED)
        or DECISION_BASIS_POLICY[a]["removed"] not in (FORBIDDEN, ALLOWED)
    ]
    result = {
        "kept_target_forbidden": kept is False,
        "removed_target_allowed": removed is True,
        "nontarget_constraints_equal": nontarget_equal,
        "no_unsatisfiable_combination": not unsatisfiable,
        "target_mechanism_contrast": kept != removed,
        "truth_table": truth_table(),
    }
    result["proof_repair_creates_contrast"] = all(
        result[k] for k in (
            "kept_target_forbidden",
            "removed_target_allowed",
            "nontarget_constraints_equal",
            "no_unsatisfiable_combination",
            "target_mechanism_contrast",
        )
    )
    return result


def assert_deductive_check() -> dict:
    r = deductive_check()
    if not r["proof_repair_creates_contrast"]:
        failed = [
            k for k, v in r.items()
            if isinstance(v, bool) and not v and k != "proof_repair_creates_contrast"
        ]
        raise PolicyContractError(f"deductive policy check failed: {failed}")
    return r


# --------------------------------------------------------------------------
# Freeze gate -- fail-closed on Q11
# --------------------------------------------------------------------------
def assert_freezable() -> None:
    """Refuse to freeze while any design question in this module is unruled.

    Q10.2's guard list is necessary but not sufficient for freezing: the
    rendering of `allowed` is a manipulation-surface choice, and P7 says the
    operating session does not make it. Encoding that as a hard stop means the
    experiment cannot silently proceed on a guess.
    """
    assert_target_axis_states()
    assert_nontarget_axes_are_arm_invariant()
    assert_arm_difference_is_exactly_the_target_set()
    assert_manipulated_axes_have_exactly_one_carrier()
    assert_deductive_check()
    if REMOVED_ALLOWED_RENDERING is None:
        raise Q11Undecided(
            "REMOVED_ALLOWED_RENDERING is None -- Q11 is unruled, so the "
            "repaired prompt surface is not yet defined and must not be "
            "frozen. See correspondence/DESIGN_REQUEST_H1a_allowed_rendering.md"
        )
